"""Render docs/claude/MASTER_MANIFEST.md from docs/claude/manifest.json.

    python3 tools/claude/manifest.py

Creation status is derived from files on disk, never from the manifest itself:
  * candidate  - models/<category>/Claude_<base_id>/model.json and its .vox exist
  * covered    - an existing Claude candidate (e.g. a pilot model) covers this entry
  * planned    - nothing generated yet
"""
from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BATCHES = {"catalog_A": "A - Household essentials", "catalog_B": "B - Building and survival",
           "catalog_C": "C - Combat and medical", "catalog_D": "D - Outdoor world",
           "catalog_E": "E - Regional map", "catalog_F": "F - Characters and enemies"}


def on_disk() -> dict[str, dict]:
    out = {}
    for mp in ROOT.glob("models/*/Claude_*/model.json"):
        m = json.loads(mp.read_text())
        if (mp.parent / m["source"]).exists():
            out[m["id"]] = m
    return out


def status_of(row, disk):
    if f"Claude_{row['base_id']}" in disk:
        return "candidate", disk[f"Claude_{row['base_id']}"]
    if row.get("existing_claude") and row["existing_claude"] in disk:
        return "covered", disk[row["existing_claude"]]
    return "planned", None


def main():
    man = json.loads((ROOT / "docs/claude/manifest.json").read_text())
    disk = on_disk()
    rows = man["assets"]
    stat = Counter()
    per_batch = defaultdict(Counter)
    lines_by_batch = defaultdict(list)
    for r in rows:
        s, m = status_of(r, disk)
        stat[s] += 1
        per_batch[r["batch"]][s] += 1
        d = r["target_dims_m"]
        actual = ""
        if m:
            ad = m["dimensions_m"]
            actual = (f"{ad[0]:g}×{ad[1]:g}×{ad[2]:g} m, {m['voxel_size_m']:g} m, "
                      f"{m['occupied_voxels']:,} vox")
        cover = r.get("existing_claude") or ""
        lines_by_batch[r["batch"]].append(
            f"| `{r['base_id']}` | {r['category']} | {r['scale']} | {r['gameplay_use']} | "
            f"{d[0]:g}×{d[1]:g}×{d[2]:g} | {r['cell_m']:g} | {r['priority']} | **{s}** | "
            f"{actual} | {('`' + cover + '`') if cover else ''} |")
    out = ["# Claude master asset manifest",
           "",
           "Generated by `tools/claude/manifest.py` from `docs/claude/manifest.json`. **Status is "
           "derived from files on disk**: an entry is only `candidate` when its `.vox` and "
           "`model.json` exist; `covered` means an existing Claude candidate (a pilot model) "
           "serves this entry instead of a duplicate. Every generated model is a **candidate** "
           "awaiting the user's review; nothing here is approved or integrated into any game.",
           "",
           "Columns: target dimensions are W × D × H in metres (planning targets); the cell column "
           "is the recommended voxel size in metres; priority P1 = needed by the game's current "
           "functionality, P2 = planned content (Experiment 003, regional map), P3 = dressing.",
           "",
           "## Progress",
           "",
           "| Batch | Entries | Candidate | Covered by existing | Planned |",
           "|---|---:|---:|---:|---:|"]
    for b, title in BATCHES.items():
        c = per_batch[b]
        out.append(f"| {title} | {sum(c.values())} | {c['candidate']} | {c['covered']} | "
                   f"{c['planned']} |")
    out.append(f"| **Total** | **{len(rows)}** | **{stat['candidate']}** | **{stat['covered']}** "
               f"| **{stat['planned']}** |")
    extra = sorted(set(disk) - {f"Claude_{r['base_id']}" for r in rows} -
                   {r.get('existing_claude') for r in rows})
    if extra:
        out += ["", "Claude candidates on disk that are not manifest entries: " +
                ", ".join(f"`{e}`" for e in extra)]
    for b, title in BATCHES.items():
        out += ["", f"## Batch {title}", "",
                "| Base ID | Category | Scale | Intended use | Target W×D×H m | Cell m | Priority | "
                "Status | Actual (if generated) | Existing Claude candidate |",
                "|---|---|---|---|---|---:|---|---|---|---|"]
        out += lines_by_batch[b]
    (ROOT / "docs/claude/MASTER_MANIFEST.md").write_text("\n".join(out) + "\n")
    print(dict(stat), "->", "docs/claude/MASTER_MANIFEST.md")


if __name__ == "__main__":
    main()
